def proposal_from_weakness(weakness: Weakness) -> ImprovementProposal | None:
    """Build a proposal for a weakness, or ``None`` when no planner answers it."""
    planner = next((p for p in _PLANNERS if weakness.kind in p.kinds), None)
    if planner is None:
        return None
    return ImprovementProposal(
        proposal_id=f"PRP-{uuid4().hex[:8]}",
        title=f"{planner.title}: {weakness.description}",
        category=planner.category,
        target_component=weakness.component,
        problem=weakness.description,
        evidence=weakness.evidence,
        proposed_change=planner.change,
        expected_benefit=planner.benefit,
        risks=planner.risks,
        required_resources=planner.resources,
        dependencies=("the project's own test suite", "an isolated Code Studio worktree"),
        expected_side_effects=planner.side_effects,
        testing_strategy=planner.testing,
        rollback_strategy=planner.rollback,
        approval_requirements=planner.approval,
        source_weakness_id=weakness.weakness_id,
        touches=planner.touches,
        complexity=planner.complexity,
    )


def generate_proposals(weaknesses: Iterable[Weakness]) -> tuple[ImprovementProposal, ...]:
    """Turn findings into proposals, strongest finding first, de-duplicated.

    Two findings of the same kind and component produce **one** proposal (a
    second identical change request would be noise), and the proposal keeps the
    stronger finding's evidence.
    """
    by_key: dict[tuple[str, str], ImprovementProposal] = {}
    for weakness in sorted(weaknesses, key=lambda w: (-w.severity.weight, -w.frequency)):
        proposal = proposal_from_weakness(weakness)
        if proposal is None:
            continue
        key = (proposal.category.value, proposal.target_component)
        if key not in by_key:
            by_key[key] = proposal
    return tuple(by_key.values())


def describe_proposals(proposals: Iterable[ImprovementProposal]) -> str:
    """Render proposals as a readable block."""
    ordered = list(proposals)
    if not ordered:
        return "No improvement proposals."
    lines = [f"{len(ordered)} proposal(s):"]
    for proposal in ordered:
        lines.append(proposal.describe())
        lines.append("")
    return "\n".join(lines).rstrip()


