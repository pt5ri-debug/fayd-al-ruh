    category: ProposalCategory
    title: str
    change: str
    benefit: str
    touches: tuple[str, ...]
    complexity: int
    risks: tuple[str, ...] = ("A code change could introduce a new regression.",)
    resources: tuple[str, ...] = ("CPU", "the project's own test suite")
    side_effects: tuple[str, ...] = ("Answers that used the affected path may change.",)
    testing: str = (
        "Run the project's own checks (pytest, ruff, mypy, evaluation) inside an "
        "isolated Code Studio worktree and compare the evaluation to the baseline."
    )
    rollback: str = (
        "Discard the worktree; the running checkout is never edited, so nothing to "
        "revert. A deployed change is reverted from its pre-deployment backup."
    )
    approval: str = "Requires the user's explicit approval before deployment."


