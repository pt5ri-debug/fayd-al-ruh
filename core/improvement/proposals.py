"""Improvement proposal generation: a structured, reviewable change request.

Section 6 of the phase lists exactly what a proposal must contain, and this
module's :class:`ImprovementProposal` carries every field of that list -- an id,
the target component, the problem, the supporting evidence, the proposed change,
the expected benefit, the risks, the required resources, the dependencies, the
expected side effects, a testing strategy, a rollback strategy, the approval
requirements, and a status.

Two rules are structural:

* **a proposal is not a change** -- nothing here edits code, weights, a dataset,
  or a configuration. A proposal is a record, and the deployment coordinator is
  the only thing that applies one, and only after a human approval; and
* **a proposal must cite a problem** -- every proposal names the weakness (or the
  measured problem) it addresses, so an improvement can always be traced back to
  the finding that motivated it (section 15).

Proposals are generated by small, deterministic *planners*: one per weakness
kind, each producing a proposal whose change is expressed as a **task
description** for the Code Studio (a git worktree), which is the isolated
execution path the project already has. A kind with no planner produces no
proposal -- the generator never invents a change it cannot describe.
"""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass, field
from datetime import UTC, datetime
from enum import Enum
from uuid import uuid4

from core.improvement.weakness import Weakness, WeaknessKind


class ProposalCategory(str, Enum):
    """The categories the phase lists -- one closed vocabulary."""

    KNOWLEDGE_SCHEMA = "knowledge_schema"
    RETRIEVAL_OPTIMIZATION = "retrieval_optimization"
    MEMORY_RANKING = "memory_ranking"
    REASONING_RULE = "reasoning_rule"
    PROCEDURE = "procedure"
    PLANNING = "planning"
    TOOL_INTEGRATION = "tool_integration"
    RESOURCE_MANAGEMENT = "resource_management"
    BUG_FIX = "bug_fix"
    DOCUMENTATION = "documentation"
    MODEL_OR_ADAPTER = "model_or_adapter"
    CONFIGURATION = "configuration"


class ProposalStatus(str, Enum):
    """Where a proposal is in its life. Mirrors the phase's change lifecycle."""

    PROPOSED = "proposed"
    AWAITING_EVALUATION = "awaiting_evaluation"
    EVALUATED = "evaluated"
    AWAITING_APPROVAL = "awaiting_approval"
    APPROVED = "approved"
    DEPLOYMENT_SCHEDULED = "deployment_scheduled"
    DEPLOYED = "deployed"
    MONITORING = "monitoring"
    ACCEPTED = "accepted"
    REJECTED = "rejected"
    ROLLED_BACK = "rolled_back"
    ARCHIVED = "archived"
    INCONCLUSIVE = "inconclusive"


#: The statuses from which a proposal must never move forward without a human
#: approval. Written down so the approval manager and the loop agree.
APPROVAL_REQUIRED_STATUSES: frozenset[ProposalStatus] = frozenset({ProposalStatus.AWAITING_APPROVAL})

#: What a proposal changes, and whether that always needs the user's explicit
#: approval (section 13). A proposal whose ``touches`` includes any of these is
#: gated regardless of its risk score.
SENSITIVE_TOUCHES: frozenset[str] = frozenset(
    {
        "source_code",
        "model_weights",
        "training_dataset",
        "permissions",
        "security",
        "database_schema",
        "irreversible",
        "private_personality_data",
    }
)


@dataclass(frozen=True)
class ImprovementProposal:
    """One structured improvement request, complete enough to review on its own."""

    proposal_id: str
    title: str
    category: ProposalCategory
    target_component: str
    problem: str
    evidence: tuple[str, ...]
    proposed_change: str
    expected_benefit: str
    risks: tuple[str, ...]
    required_resources: tuple[str, ...]
    dependencies: tuple[str, ...]
    expected_side_effects: tuple[str, ...]
    testing_strategy: str
    rollback_strategy: str
    approval_requirements: str
    status: ProposalStatus = ProposalStatus.PROPOSED
    source_weakness_id: str | None = None
    #: What the proposal would touch, drawn from :data:`SENSITIVE_TOUCHES` plus
    #: ordinary tags like ``configuration`` or ``docs``. Used by the approval
    #: manager to decide whether the change is always gated.
    touches: tuple[str, ...] = ()
    #: A rough complexity in 1..5 (1 is a one-line change, 5 a redesign). Kept
    #: explicit so prioritization can use it without guessing.
    complexity: int = 2
    created_at: datetime = field(default_factory=lambda: datetime.now(UTC))

    def __post_init__(self) -> None:
        if not self.title.strip():
            raise ValueError("A proposal must have a title.")
        if not 1 <= self.complexity <= 5:
            raise ValueError("A proposal's complexity must be between 1 and 5.")
        if not self.problem.strip():
            raise ValueError("A proposal must name the problem it addresses.")

    @property
    def requires_explicit_approval(self) -> bool:
        """True when the change always needs the user's explicit approval."""
        return bool(set(self.touches) & SENSITIVE_TOUCHES)

    @property
    def is_code_change(self) -> bool:
        return "source_code" in self.touches or self.category in {
            ProposalCategory.BUG_FIX,
            ProposalCategory.RETRIEVAL_OPTIMIZATION,
            ProposalCategory.REASONING_RULE,
            ProposalCategory.PLANNING,
            ProposalCategory.MEMORY_RANKING,
            ProposalCategory.KNOWLEDGE_SCHEMA,
        }

    def with_status(self, status: ProposalStatus) -> ImprovementProposal:
        """A copy at a new status (a proposal is a record, not a mutable object)."""
        return _replace(self, status=status)

    def to_primitive(self) -> dict[str, object]:
        return {
            "proposal_id": self.proposal_id,
            "title": self.title,
            "category": self.category.value,
            "target_component": self.target_component,
            "problem": self.problem,
            "evidence": list(self.evidence),
            "proposed_change": self.proposed_change,
            "expected_benefit": self.expected_benefit,
            "risks": list(self.risks),
            "required_resources": list(self.required_resources),
            "dependencies": list(self.dependencies),
            "expected_side_effects": list(self.expected_side_effects),
            "testing_strategy": self.testing_strategy,
            "rollback_strategy": self.rollback_strategy,
            "approval_requirements": self.approval_requirements,
            "status": self.status.value,
            "source_weakness_id": self.source_weakness_id,
            "touches": list(self.touches),
            "complexity": self.complexity,
            "created_at": self.created_at.isoformat(),
            "requires_explicit_approval": self.requires_explicit_approval,
        }

    def describe(self) -> str:
        return (
            f"{self.proposal_id} [{self.category.value}] {self.title}\n"
            f"  target: {self.target_component}\n"
            f"  problem: {self.problem}\n"
            f"  change: {self.proposed_change}\n"
            f"  benefit: {self.expected_benefit}\n"
            f"  status: {self.status.value}"
        )


def _replace(proposal: ImprovementProposal, **changes: object) -> ImprovementProposal:
    """A tiny, dependency-free dataclass replace (avoids importing ``dataclasses.replace``)."""
    import dataclasses

    return dataclasses.replace(proposal, **changes)  # type: ignore[arg-type]


#: A planner: which weakness kinds it answers, and how it builds a proposal.
